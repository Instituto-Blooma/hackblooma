/**
 * Lista oficial 2026, from the Equipe Blooma spreadsheet "Agenda de Olimpíadas - Lista".
 * Later Fases the sheet does not list are "a confirmar" with the usual month as the estimate.
 */

type SeedPhase = { name: string; date: DateInfo };

export type SeedOlympiad = {
  key: string;
  name: string;
  acronym: string;
  area: string;
  website?: string;
  registrationDeadline?: DateInfo;
  registrationNote?: string;
  eligibility?: Eligibility;
  leadsTo?: string[];
  phases: SeedPhase[];
};

function day(start: string, end?: string, note?: string): DateInfo {
  return {
    status: 'confirmed',
    start: `2026-${start}`,
    end: end ? `2026-${end}` : undefined,
    note,
  };
}

function tbc(estimateMonth?: number, note?: string): DateInfo {
  return { status: 'tbc', estimateMonth, note };
}

